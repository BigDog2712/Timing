-- =============================================================================
-- Timing 数据库迁移 0006（V0.11.13）
-- -----------------------------------------------------------------------------
-- 变更：新建 `md_cloud_pending` —— 云端通道的待传队列。
-- 版本：schema.version = 6
--
-- 【为什么需要这张表】
--   云端通道「只同步当天」，某天手机没联网、没传成功，第二天按「只同步当天」就
--   永远不补，那天的账只留在手机上，直到某天发现 PC 上少了一段。所以判据不能是
--   日期窗口，而是「有没有还没传成功的改动」——这个状态必须活过进程重启。
--
-- 【为什么不塞进 settings 的 JSON】
--   `settings` 是整块读写的 KV：同步轮与设置页同时改会丢更新，而这里每一行是
--   「某一天传没传成功」的独立事实，本来就应该按行更新。
--
-- 【三列的含义】
--   `etag`        上次成功同步时远端的 ETag（NULL = 远端还没有这天）。下次 PUT 用它
--                 做 `If-Match`，挡住「你改的时候我也在改」；
--   `last_hash`   上次记下的内容指纹（FNV-1a 64，16 位十六进制）。判据是**文件内容**
--                 而不是「谁最后碰过文件」——坚果云客户端会改 mtime，用 mtime 判定
--                 必然把「用户什么都没改」误判成外部改动（ADR-042）；
--   `pending_since` 第一次发现有未传改动的时间（毫秒），**0 = 无欠账**。非 0 时
--                 下一次同步必须补传这一天。
--
-- 只 `CREATE TABLE IF NOT EXISTS` + 推进版本号，不 ALTER 既有表（K-13）：
-- 这张表在 v5 及更老的库里根本不存在，没有「补列」可言。
-- =============================================================================

CREATE TABLE IF NOT EXISTS md_cloud_pending (
  date          TEXT PRIMARY KEY,              -- yyyy-MM-dd（本地时区，不许用 UTC 日期）
  etag          TEXT,                          -- 上次成功同步时远端的 ETag
  last_hash     TEXT,                          -- 上次记下的内容指纹
  pending_since INTEGER NOT NULL DEFAULT 0     -- 0 = 无欠账
);

-- -----------------------------------------------------------------------------
-- 版本推进：schema.version = 6
-- -----------------------------------------------------------------------------
UPDATE settings SET value = '6', updated_at = CAST(strftime('%s','now') AS INTEGER) * 1000
WHERE key = 'schema.version';
