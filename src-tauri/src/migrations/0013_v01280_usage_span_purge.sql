-- =============================================================================
-- Timing 业务库迁移 0013（0.12.8 · 清掉配对算法修正前写下的碎段）—— **一次性段**
--
-- 由 `infra/migrate.rs::migrate()` 在 `schema_version(pool) < 13` 时执行一次。
--
-- ## 为什么必须清
-- 0.12.5–0.12.7 的配对口径是「`ACTIVITY_PAUSED` 即离开」。同一个应用内部换 Activity
-- （微信从视频页回聊天页、游戏过场、系统权限弹窗回来）也是一串**同一毫秒**到达的
-- RESUMED / PAUSED，于是**一次连续使用被切成上百条「09:01 - 09:01」的碎段**写进这张表。
-- 用户反馈的「多段不到一分钟计时」就是它，不是采集没采到。
--
-- 0.12.8 改成「只认另一个包 RESUMED / 息屏锁屏」，算出来的段**起点完全不同**。而
-- `services::usage::rollup` 是逐条 `ON CONFLICT ... end_ms = MAX`：新旧两批段会并存，
-- 读出来再合并成一张更乱的时间轴，而且**不会报任何错** —— 只能靠这一次清理断干净。
--
-- ## 为什么可以整表清空
-- 这张表只存「配对后的区间」，唯一用途是给界面列时段。清空的代价是丢掉一段本来就错的
-- 历史；正确的历史在下次打开页面时按新口径重新写回（系统保留约 7 天明细），
-- 7 天之前的段连同它的错误一起消失。
--
-- ## `app_usage`（合计）为什么不在这里清
-- 0.12.8 起 `services::usage::rollup` 改成**整天重算**（先清后写），不再取 MAX。所以
-- 旧算法写下的虚高值不需要迁移处理：界面每次打开这些日期都会用新口径覆盖一遍。
-- 反过来，在这里清 `app_usage` 会把 7 天之前、系统明细已经回收、永远无法重算的那些天
-- 一起抹掉 —— 那是真正的数据丢失，换不来任何准确度。
-- =============================================================================

DELETE FROM app_usage_span;

UPDATE settings SET value = '13', updated_at = CAST(strftime('%s','now') AS INTEGER) * 1000
WHERE key = 'schema.version';
