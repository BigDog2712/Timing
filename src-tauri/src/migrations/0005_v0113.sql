-- =============================================================================
-- Timing 数据库迁移 0005（V0.11.3）
-- -----------------------------------------------------------------------------
-- 变更：todos 增加 `item_id` —— 待办绑定到具体事项，不再每次开始计时时靠标题猜。
-- 版本：schema.version = 5
--
-- 【为什么现在才绑】
--   V0.3.12 起，待办开始计时是「按标题匹配事项，没有就新建」。它的问题不在创建，
--   而在**之后**：用户把待办标题改成「周报（二稿）」，再开始计时就会新建一个同名
--   事项，同一件事在统计里裂成两条。绑定 item_id 之后，标题只是显示名，改它不再
--   影响归属。
--
-- 【为什么可空】
--   1) 老数据没有绑定，全表回填等于重跑一次「按标题匹配」，而标题可能撞车
--      （两条同名待办绑到同一事项，未必是用户想要的）；
--   2) 新建待办时也允许没有对应事项——用户可能先记一笔，还没想好归到哪。
--   空值由 `todo_start` 兜底：第一次开始计时时按标题匹配/新建，**并回填**，
--   此后这条待办就固定绑定了。
--
-- 【为什么加列不写在本文件里】
--   SQLite 不支持 `ALTER TABLE ... ADD COLUMN IF NOT EXISTS`，重复执行会报
--   `duplicate column name`（K-13）。加列由 `infra::migrate::ensure_column`
--   以 `PRAGMA table_info` 守卫执行（见 MIGRATE_COLUMNS_V5），本文件只做版本推进。
--
-- 【为什么建了索引】
--   待办列表按事项反查（「这个事项还有哪些待办」）以及按 item_id 归组统计都要它；
--   空值不进索引，代价只有非空行。
-- =============================================================================

CREATE INDEX IF NOT EXISTS idx_todos_item ON todos(item_id) WHERE item_id IS NOT NULL;

-- -----------------------------------------------------------------------------
-- 版本推进：schema.version = 5
-- -----------------------------------------------------------------------------
UPDATE settings SET value = '5', updated_at = CAST(strftime('%s','now') AS INTEGER) * 1000
WHERE key = 'schema.version';
